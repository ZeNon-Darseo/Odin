const CATEGORY_KEYS = {
  'Ванны и сказки': 'baths',
  'Массажи и забота': 'massage',
  'Красота и грим': 'beauty',
  'Праздники и программы': 'party',
};

function detectLang() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (LANGS.includes(stored)) return stored;
  } catch { /* storage may be blocked */ }
  const candidates = [navigator.language, ...(navigator.languages ?? [])];
  for (const candidate of candidates) {
    const code = String(candidate || '').slice(0, 2).toLowerCase();
    if (LANGS.includes(code)) return code;
  }
  return 'ru';
}

let current = detectLang();

function lookup(dict, key) {
  return key.split('.').reduce((node, part) => (node == null ? undefined : node[part]), dict);
}

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!LANGS.includes(lang)) return current;
  current = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
  return current;
}

export function has(key) {
  return lookup(ru, key) !== undefined;
}

export function t(key, params = {}) {
  const value = lookup(DICTS[current], key) ?? lookup(ru, key);
  if (typeof value !== 'string') return key;
  return value.replace(/\{(\w+)\}/g, (match, name) => (params[name] ?? match));
}

export function tList(key) {
  const value = lookup(DICTS[current], key) ?? lookup(ru, key);
  return Array.isArray(value) ? value : [];
}

export function locale() {
  return LOCALES[current] ?? LOCALES.ru;
}

export function fmtNumber(value) {
  return new Intl.NumberFormat(locale()).format(Number(value) || 0);
}

export function fmtPrice(value) {
  return `${fmtNumber(value)} ₸`;
}

export function plural(key, count) {
  const forms = lookup(DICTS[current], `plural.${key}`) ?? lookup(ru, `plural.${key}`);
  if (!forms) return String(count);
  const category = new Intl.PluralRules(locale()).select(Number(count));
  return `${fmtNumber(count)} ${forms[category] ?? forms.other ?? forms.many}`;
}

export function ageText(value) {
  return plural('years', value);
}

const WEEKDAY = {};
const MONTH = {};

function weekdayName(date) {
  const loc = locale();
  WEEKDAY[loc] ??= new Intl.DateTimeFormat(loc, { weekday: 'short' });
  return WEEKDAY[loc].format(date);
}

function monthName(date, style = 'long') {
  const loc = locale();
  MONTH[loc] ??= {};
  MONTH[loc][style] ??= new Intl.DateTimeFormat(loc, { month: style });
  return MONTH[loc][style].format(date);
}

export function fmtDate(iso, { weekday = false, year = false } = {}) {
  if (!iso) return '';
  const date = new Date(`${String(iso).slice(0, 10)}T00:00:00`);
  if (Number.isNaN(date.getTime())) return String(iso);
  const base = `${date.getDate()} ${monthName(date)}${year ? ` ${date.getFullYear()}` : ''}`;
  return weekday ? `${weekdayName(date)}, ${base}` : base;
}

export function dayLabel(iso) {
  const date = new Date(`${iso}T00:00:00`);
  return {
    top: weekdayName(date),
    bottom: String(date.getDate()),
    month: monthName(date, 'short').replace(/\.$/, ''),
  };
}

export function fmtDuration(min) {
  if (min < 60) return `${min} ${t('ui.min')}`;
  if (min % 60 === 0) return `${min / 60} ${t('ui.hour')}`;
  return `${Math.floor(min / 60)} ${t('ui.hour')} ${min % 60} ${t('ui.min')}`;
}

export function categoryLabel(category) {
  const key = CATEGORY_KEYS[category];
  return key ? t(`cat.${key}`) : category;
}

export function categoryKey(category) {
  return CATEGORY_KEYS[category] ?? '';
}

export function localized(record, field) {
  if (!record) return '';
  if (current === 'kk' && record[`${field}_kk`]) return record[`${field}_kk`];
  if (current === 'en' && record[`${field}_en`]) return record[`${field}_en`];
  return record[field] ?? '';
}

export const serviceTitle = (service) => localized(service, 'title');
export const serviceDescription = (service) => localized(service, 'description');
